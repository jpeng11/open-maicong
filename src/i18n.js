  let locale = 'zh';

  function normalizeLocale(value) {
    if (value === 'en' || value === 'zh') return value;
    if (typeof value === 'string' && value.toLowerCase().startsWith('en')) return 'en';
    return 'zh';
  }

  function t(key, vars) {
    const dict = STRINGS[locale] || STRINGS.zh;
    const fallback = (STRINGS.zh && STRINGS.zh[key]) || (STRINGS.en && STRINGS.en[key]) || (vars && vars.default) || key;
    let text = Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : fallback;
    if (vars && typeof text === 'string') {
      text = text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] == null ? '' : String(vars[name])));
    }
    return text;
  }

  function setLocale(next) {
    locale = normalizeLocale(next);
    return locale;
  }

  function getLocale() {
    return locale;
  }

  function apply(root) {
    const doc = root && root.querySelectorAll ? root : (typeof document !== 'undefined' ? document : null);
    if (!doc) return locale;
    const scope = root && root.querySelectorAll ? root : document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
      document.title = t('app.documentTitle');
    }
    const zhBtn = typeof document !== 'undefined' ? document.getElementById('lang-zh') : null;
    const enBtn = typeof document !== 'undefined' ? document.getElementById('lang-en') : null;
    if (zhBtn) zhBtn.classList.toggle('active', locale === 'zh');
    if (enBtn) enBtn.classList.toggle('active', locale === 'en');
    return locale;
  }

  return {
    STRINGS,
    DEFAULT_LOCALE: 'zh',
    t,
    setLocale,
    getLocale,
    normalizeLocale,
    apply
  };
